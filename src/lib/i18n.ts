export const translations: Record<Language, typeof en> = { en, te };

export function getGreeting(lang: Language): string {
  const hour = new Date().getHours();
  if (lang === 'te') {
    if (hour < 12) return 'శుభోదయం!';
    if (hour < 17) return 'శుభ మధ్యాహ్నం!';
    return 'శుభ సాయంత్రం!';
  }
  if (hour < 12) return 'Good morning!';
  if (hour < 17) return 'Good afternoon!';
  return 'Good evening!';
}
